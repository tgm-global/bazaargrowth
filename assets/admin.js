/* Site Settings generator: builds a new config.js from the form. Nothing is sent anywhere. */
(function () {
  "use strict";
  var C = window.SITE_CONFIG || {};
  var $ = function (id) { return document.getElementById(id); };
  var digits = function (v) { return String(v || "").replace(/\D/g, ""); };
  var ids = { brandName: "sBrand", tagline: "sTagline", phone: "sPhone", whatsapp: "sWhatsapp", email: "sEmail", w3formsToken: "sToken", testimonialsApi: "sTApi", testimonialsKey: "sTKey", affiliateLink: "sAff", affiliateLabel: "sAffLabel" };
  Object.keys(ids).forEach(function (k) { $(ids[k]).value = C[k] || ""; });
  var soc = C.social || {}, socIds = { facebook: "sFb", instagram: "sIg", youtube: "sYt", linkedin: "sLi", twitter: "sTw", telegram: "sTg" };
  Object.keys(socIds).forEach(function (k) { $(socIds[k]).value = soc[k] || ""; });
  $("sShowPhone").checked = C.showPhoneAndWhatsapp !== false;
  $("sShowForm").checked = C.showEmailFormAndTestimonials !== false;
  $("sTItems").value = (C.testimonialsItems || []).map(function (t) { return [t.name, t.role, t.text].join(" | "); }).join("\n");

  function build() {
    var items = $("sTItems").value.split("\n").map(function (l) { return l.trim(); }).filter(Boolean).map(function (l) {
      var p = l.split("|").map(function (x) { return x.trim(); });
      return { name: p[0] || "", role: p.length > 2 ? p[1] : "", text: p.length > 2 ? p.slice(2).join(" | ") : (p[1] || "") };
    });
    var o = {
      brandName: $("sBrand").value.trim() || "Bazar Growth",
      tagline: $("sTagline").value.trim(),
      phone: digits($("sPhone").value).slice(-10),
      whatsapp: digits($("sWhatsapp").value).slice(-10),
      countryCode: C.countryCode || "91",
      email: $("sEmail").value.trim(),
      w3formsToken: $("sToken").value.trim(),
      testimonialsApi: $("sTApi").value.trim(),
      testimonialsKey: $("sTKey").value.trim(),
      testimonialsItems: items,
      affiliateLink: $("sAff").value.trim(),
      affiliateLabel: $("sAffLabel").value.trim() || "Recommended partner offer",
      social: (function () { var s = {}; Object.keys(socIds).forEach(function (k) { s[k] = $(socIds[k]).value.trim(); }); return s; })(),
      showPhoneAndWhatsapp: $("sShowPhone").checked,
      showEmailFormAndTestimonials: $("sShowForm").checked
    };
    return "/* GLOBAL CONFIGURATION HUB: generated by admin.html. Paste this over config.js. */\nwindow.SITE_CONFIG = " + JSON.stringify(o, null, 2) + ";\n";
  }
  var out = $("cfgOut");
  function refresh() { out.value = build(); }
  Array.prototype.forEach.call(document.querySelectorAll("#settingsForm input, #settingsForm textarea"), function (el) { el.addEventListener("input", refresh); });
  $("settingsForm").addEventListener("submit", function (e) { e.preventDefault(); });
  refresh();

  /* publish config.js straight to GitHub (token is used once in this browser and never stored) */
  var gOwner = $("gOwner"), gRepo = $("gRepo"), gBranch = $("gBranch"), gToken = $("gToken"), pubOut = $("pubOut");
  try { var sv = JSON.parse(localStorage.getItem("bgGit") || "{}"); gOwner.value = sv.owner || ""; gRepo.value = sv.repo || ""; gBranch.value = sv.branch || "main"; } catch (e) { gBranch.value = "main"; }
  var say = function (m, bad) { pubOut.innerHTML = '<div class="msg' + (bad ? " err" : "") + '" role="status"></div>'; pubOut.firstChild.textContent = m; };
  $("pubGit").addEventListener("click", function () {
    var owner = gOwner.value.trim(), repo = gRepo.value.trim(), branch = gBranch.value.trim() || "main", token = gToken.value.trim();
    if (!owner || !repo || !token) { say("Enter your GitHub username, repository name and token first.", true); return; }
    try { localStorage.setItem("bgGit", JSON.stringify({ owner: owner, repo: repo, branch: branch })); } catch (e) {}
    var api = "https://api.github.com/repos/" + encodeURIComponent(owner) + "/" + encodeURIComponent(repo) + "/contents/config.js";
    var h = { "Authorization": "Bearer " + token, "Accept": "application/vnd.github+json" };
    var btn = $("pubGit"); btn.disabled = true; say("Publishing...");
    fetch(api + "?ref=" + encodeURIComponent(branch), { headers: h }).then(function (r) {
      if (r.status === 404) return null;
      if (!r.ok) throw new Error(r.status === 401 || r.status === 403 ? "GitHub rejected the token. It needs Contents: Read and write access for this repository." : "Could not read config.js (error " + r.status + ").");
      return r.json();
    }).then(function (cur) {
      var body = { message: "Update site settings from admin page", content: btoa(unescape(encodeURIComponent(out.value))), branch: branch };
      if (cur && cur.sha) body.sha = cur.sha;
      return fetch(api, { method: "PUT", headers: h, body: JSON.stringify(body) });
    }).then(function (r) {
      if (!r.ok) throw new Error(r.status === 401 || r.status === 403 ? "GitHub rejected the token. It needs Contents: Read and write access for this repository." : "GitHub could not save the file (error " + r.status + ").");
      say("Published. GitHub Pages rebuilds in about a minute, then every page shows the new settings.");
      gToken.value = "";
    }).catch(function (err) { say(err.message || "Network problem. Please try again.", true); }).then(function () { btn.disabled = false; });
  });

  $("copyCfg").addEventListener("click", function () {
    var b = $("copyCfg");
    var done = function (ok) { b.textContent = ok ? "Copied" : "Select the text and copy it"; if (!ok) { out.focus(); out.select(); } setTimeout(function () { b.textContent = "Copy config.js"; }, 2200); };
    try { navigator.clipboard.writeText(out.value).then(function () { done(true); }, function () { done(false); }); } catch (e) { done(false); }
  });
  $("dlCfg").addEventListener("click", function () {
    var url = URL.createObjectURL(new Blob([out.value], { type: "text/javascript" }));
    var a = document.createElement("a"); a.href = url; a.download = "config.js";
    document.body.appendChild(a); a.click(); a.remove(); setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
  });
})();
